// Writes src/zone_cells.js: for each zone, the H3 resolution-4 cells (gpsjam.org's grid) whose centre lies inside the
// zone circle. A cell inside two circles goes to the nearer centre. Run after changing src/zones.js: `npm run gen-cells`.
// `--check` fails when the committed file is out of date (CI runs it).
import { readFileSync, writeFileSync } from "node:fs";
import { cellToLatLng, polygonToCells } from "h3-js";
import { distanceKm as km } from "../src/metric.js";
import { ZONES } from "../src/zones.js";

const NM_KM = 1.852;
const OUT = new URL("../src/zone_cells.js", import.meta.url);

function circle(z, pad = 1.1) {
  const R = 6371;
  const d = (z.r_nm * NM_KM * pad) / R;
  const lat1 = (z.lat * Math.PI) / 180;
  const lon1 = (z.lon * Math.PI) / 180;
  const ring = [];
  for (let i = 0; i < 64; i++) {
    const b = (2 * Math.PI * i) / 64;
    const lat2 = Math.asin(Math.sin(lat1) * Math.cos(d) + Math.cos(lat1) * Math.sin(d) * Math.cos(b));
    const lon2 = lon1 + Math.atan2(Math.sin(b) * Math.sin(d) * Math.cos(lat1), Math.cos(d) - Math.sin(lat1) * Math.sin(lat2));
    ring.push([(lat2 * 180) / Math.PI, (lon2 * 180) / Math.PI]);
  }
  return ring;
}

const owner = new Map(); // cell -> {zone, d}
for (const z of ZONES) {
  for (const cell of polygonToCells(circle(z), 4)) {
    const [lat, lon] = cellToLatLng(cell);
    const d = km(lat, lon, z.lat, z.lon);
    if (d > z.r_nm * NM_KM) continue;
    const prev = owner.get(cell);
    if (!prev || d < prev.d) owner.set(cell, { zone: z.id, d });
  }
}
const cells = Object.fromEntries(ZONES.map((z) => [z.id, []]));
for (const [cell, { zone }] of owner) cells[zone].push(cell);
for (const id in cells) cells[id].sort();

const body =
  "// Generated by `npm run gen-cells` from src/zones.js. Do not edit by hand.\n" +
  "// H3 resolution-4 cells (gpsjam.org's grid) whose centre lies inside each zone circle.\n" +
  `export const ZONE_CELLS = {\n${Object.entries(cells).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n")}\n};\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== body) {
    console.error("src/zone_cells.js is out of date with src/zones.js. Run `npm run gen-cells` and commit the result.");
    process.exit(1);
  }
  console.log("zone cells up to date");
} else {
  writeFileSync(OUT, body);
  console.log(Object.entries(cells).map(([k, v]) => `${k}: ${v.length}`).join(", "));
}
