// Detection power of the frozen rule (spec S5): inject a bad fraction into clean samples and count DEGRADED.
// Seeded, so the output is reproducible: `npm run power` writes docs/POWER.md and src/power.js; `--check` fails
// when either is out of date (npm test runs it). It never fails because S5 misses: the page shows the miss.
import { readFileSync, writeFileSync } from "node:fs";
import { DEGRADED_MIN_BAD } from "../src/config.js";
import { classify } from "../src/metric.js";
import { RULES } from "../src/method.js";
import { ZONE_BY_ID } from "../src/zones.js";

const FRACTIONS = [0, 0.02, 0.05, 0.1, 0.15, 0.2, 0.4];
const SIZES = [15, 30, 60];
const DRAWS = 1000;
const MIN_N = ZONE_BY_ID.get("baltic").min_n; // the positive control's minimum
const TYPES = ["B738", "A320", "B77W", "E190", "A21N", "B789", "A333", "B38M"];

function mulberry32(seed) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function degradedShare(f, n, rand) {
  let hits = 0;
  let pairs = 0;
  let prev = false;
  for (let d = 0; d < DRAWS; d++) {
    let bad = 0;
    const types = new Set();
    for (let i = 0; i < n; i++) {
      if (rand() < f) {
        bad++;
        types.add(TYPES[Math.floor(rand() * TYPES.length)]);
      }
    }
    const deg = classify({ n_elig: n, n_bad: bad, types_bad: types.size }, MIN_N) === "DEGRADED";
    if (deg) hits++;
    if (d % 2 === 1 && deg && prev) pairs++;
    prev = deg;
  }
  return { sample: hits / DRAWS, onset: pairs / (DRAWS / 2) };
}

const rand = mulberry32(20261015);
const table = FRACTIONS.map((f) => ({ f, cells: SIZES.map((n) => ({ n, ...degradedShare(f, n, rand) })) }));
const at = (f, n) => table.find((r) => r.f === f).cells.find((c) => c.n === n);
const detect = at(0.15, 30).sample;
const falseRate = at(0.02, 30).sample;
const TARGET = { detect: 0.9, falseRate: 0.02 }; // spec S5
const pass = detect >= TARGET.detect && falseRate <= TARGET.falseRate;
const pc = (x) => `${(100 * x).toFixed(1)}%`;
const target = `at least ${100 * TARGET.detect}% detection at 15% bad with n = 30, and at most ${100 * TARGET.falseRate}% false DEGRADED at 2% bad`;

const md = `# Detection power

Generated by \`npm run power\` (seeded, ${DRAWS} draws per cell, ${TYPES.length} aircraft types). Do not edit by hand.

Each draw is one zone sample of *n* eligible aircraft where each aircraft is bad with probability *f*. A cell shows how often the frozen rule classes that sample **DEGRADED** (${RULES.degraded}). In brackets: how often two samples in a row are both DEGRADED, which is what an onset needs.

| bad fraction | ${SIZES.map((n) => `n = ${n}`).join(" | ")} |
|---|${SIZES.map(() => "---").join("|")}|
${table.map((r) => `| ${pc(r.f)} | ${r.cells.map((c) => `${pc(c.sample)} (${pc(c.onset)})`).join(" | ")} |`).join("\n")}

## S5

Target: ${target}.
Measured: **${pc(detect)}** detection and **${pc(falseRate)}** false. **${pass ? "Pass" : "Miss"}.**

${pass ? "" : `The rule is frozen (docs/METHOD.md), so a miss is reported here and on the page rather than tuned away. At n = 30 a DEGRADED sample needs ${DEGRADED_MIN_BAD} bad aircraft; at 15% bad the average is ${0.15 * 30}, so some samples fall short. At 20% bad, n = 30 detects ${pc(at(0.2, 30).sample)} of samples.\n`}
## False onsets

An onset needs two DEGRADED samples in a row. If a quiet zone's samples are independent, the chance of a false onset in any one slot is about the false-sample rate squared, and a zone has 144 slots a day. At 2% bad that is **${(at(0.02, 30).sample ** 2 * 144).toFixed(2)}** false onsets per zone per day at n = 30 and ${(at(0.02, 60).sample ** 2 * 144).toFixed(3)} at n = 60, or about **${(at(0.02, 30).sample ** 2 * 144 * 12).toFixed(1)}** a day across 12 sentinels if every one sat at 2% with 30 aircraft. Real samples ten minutes apart share many aircraft, so they aren't independent, and false onsets are not filtered out: every one is logged and listed. The controls measure the real rate (S3).
`;

const js = `// Generated by \`npm run power\`. Do not edit by hand.
export const POWER = ${JSON.stringify({ target, detect15n30: detect, false2n30: falseRate, pass, table })};
`;

const MD = new URL("../docs/POWER.md", import.meta.url);
const JS = new URL("../src/power.js", import.meta.url);
if (process.argv.includes("--check")) {
  const stale = [[MD, md], [JS, js]].filter(([u, body]) => {
    try {
      return readFileSync(u, "utf8") !== body;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error("docs/POWER.md or src/power.js is out of date. Run `npm run power` and commit the result.");
    process.exit(1);
  }
  console.log(`power table up to date (S5 ${pass ? "pass" : "miss"})`);
} else {
  writeFileSync(MD, md);
  writeFileSync(JS, js);
  console.log(md);
}
